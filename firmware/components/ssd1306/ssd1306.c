/* ── Low-level helpers ───────────────────────────────────────────────────── */

static esp_err_t send_cmd(uint8_t cmd)
{
    uint8_t buf[2] = {CTRL_CMD, cmd};
    return i2c_master_transmit(s_dev, buf, sizeof(buf), I2C_TIMEOUT_MS);
}

static esp_err_t send_data(const uint8_t *data, size_t len)
{
    /* Prepend the data-stream control byte */
    uint8_t buf[len + 1];
    buf[0] = CTRL_DATA;
    memcpy(&buf[1], data, len);
    return i2c_master_transmit(s_dev, buf, len + 1, I2C_TIMEOUT_MS);
}

/* ── SSD1306 initialisation sequence ────────────────────────────────────── */
static const uint8_t INIT_CMDS[] = {
    0xAE,       /* display off                        */
    0xD5, 0x80, /* clock divide ratio / osc frequency */
    0xA8, 0x3F, /* multiplex ratio = 64               */
    0xD3, 0x00, /* display offset = 0                 */
    0x40,       /* start line = 0                     */
    0x8D, 0x14, /* charge pump enable                 */
    0x20, 0x00, /* memory addressing mode: horizontal */
    0xA1,       /* segment remap (flip horizontally)  */
    0xC8,       /* COM scan direction remapped        */
    0xDA, 0x12, /* COM pins hardware config           */
    0x81, 0xCF, /* contrast                           */
    0xD9, 0xF1, /* pre-charge period                  */
    0xDB, 0x40, /* VCOMH deselect level               */
    0xA4,       /* entire display ON (follow RAM)      */
    0xA6,       /* normal display (not inverted)       */
    0xAF,       /* display on                          */
};

/* ── Public API ──────────────────────────────────────────────────────────── */

esp_err_t ssd1306_init(void)
{
    if (s_dev != NULL) return ESP_ERR_INVALID_STATE;

    const i2c_device_config_t dev_cfg = {
        .dev_addr_length = I2C_ADDR_BIT_LEN_7,
        .device_address  = BOARD_I2C_ADDR_SSD1306,
        .scl_speed_hz    = 400000,
    };
    esp_err_t err = i2c_master_bus_add_device(i2c_bus_get(), &dev_cfg, &s_dev);
    if (err != ESP_OK) {
        ESP_LOGE(TAG, "add device failed: %s", esp_err_to_name(err));
        return err;
    }

    for (size_t i = 0; i < sizeof(INIT_CMDS); i++) {
        err = send_cmd(INIT_CMDS[i]);
        if (err != ESP_OK) {
            ESP_LOGE(TAG, "init cmd 0x%02X failed: %s", INIT_CMDS[i], esp_err_to_name(err));
            goto fail;
        }
    }

    err = ssd1306_clear();
    if (err != ESP_OK) goto fail;

    ESP_LOGI(TAG, "init OK (128x64)");
    return ESP_OK;

fail:
    i2c_master_bus_rm_device(s_dev);
    s_dev = NULL;
    return err;
}

esp_err_t ssd1306_clear(void)
{
    if (s_dev == NULL) return ESP_ERR_INVALID_STATE;
    uint8_t blank[OLED_WIDTH];
    memset(blank, 0x00, sizeof(blank));
    for (uint8_t page = 0; page < OLED_PAGES; page++) {
        send_cmd(0xB0 | page);  /* set page address */
        send_cmd(0x00);         /* column low nibble = 0 */
        send_cmd(0x10);         /* column high nibble = 0 */
        esp_err_t err = send_data(blank, sizeof(blank));
        if (err != ESP_OK) return err;
    }
    return ESP_OK;
}

esp_err_t ssd1306_write_line(uint8_t row, const char *text)
{
    if (s_dev == NULL || text == NULL) return ESP_ERR_INVALID_ARG;
    if (row >= OLED_PAGES) return ESP_ERR_INVALID_ARG;

    /* Render the text into a 128-byte page buffer */
    uint8_t page_buf[OLED_WIDTH];
    memset(page_buf, 0x00, sizeof(page_buf));

    size_t len = strlen(text);
    if (len > CHARS_PER_ROW) len = CHARS_PER_ROW;

    for (size_t col = 0; col < len; col++) {
        uint8_t ch = (uint8_t)text[col];
        if (ch < 0x20 || ch > 0x7E) ch = 0x20;  /* replace non-printable */
        const uint8_t *glyph = FONT8x8[ch - 0x20];
        /* The SSD1306 in horizontal mode writes column pixels top→bottom.  *
         * Our font stores row pixels left→right, so we transpose here.     */
        for (int px = 0; px < 8; px++) {
            uint8_t byte = 0;
            for (int row_bit = 0; row_bit < 8; row_bit++) {
                if (glyph[row_bit] & (0x80 >> px)) {
                    byte |= (1 << row_bit);
                }
            }
            page_buf[col * 8 + px] = byte;
        }
    }

    /* Set page and column address, then write the row */
    send_cmd(0xB0 | row);
    send_cmd(0x00);
    send_cmd(0x10);
    return send_data(page_buf, sizeof(page_buf));
}
